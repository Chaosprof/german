def fill_blanks(file_path, key_in_doc, key_in_arr, mapping):
    doc = json.loads(file_path.read_text(encoding='utf-8'))
    arr = doc[key_in_doc]
    by_word = {item['word']: item for item in arr}
    filled = 0
    not_found = []
    not_blank = 0
    for word, en in mapping.items():
        item = by_word.get(word)
        if not item:
            not_found.append(word)
            continue
        if item.get('english', '').strip():
            not_blank += 1
            continue
        item['english'] = en
        filled += 1
    file_path.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return filled, not_blank, not_found


def main():
    print('Filling noun blanks...')
    f, nb, nf = fill_blanks(ROOT/'data'/'nouns.json', 'nouns', 'word', NOUN_BLANKS)
    print(f"  filled: {f}, already-filled: {nb}, not-in-dataset: {len(nf)}")

    print('Filling adjective blanks...')
    f, nb, nf = fill_blanks(ROOT/'data'/'adjectives.json', 'adjectives', 'word', ADJECTIVE_BLANKS)
    print(f"  filled: {f}, already-filled: {nb}, not-in-dataset: {len(nf)}")


if __name__ == '__main__':
    main()
