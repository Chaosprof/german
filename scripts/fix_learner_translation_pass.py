def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def save(path: Path, doc: dict) -> None:
    path.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def apply_fixes(path: Path, key: str, fixes: dict[str, str]) -> tuple[list[dict], list[dict]]:
    doc = load(path)
    changed = []
    reviewed = []
    found = set()
    for row in doc[key]:
        word = row.get("word")
        if word not in fixes:
            continue
        found.add(word)
        new = fixes[word]
        old = row.get("english", "")
        reviewed.append(
            {
                "rank": row.get("rank"),
                "article": row.get("article") or "",
                "word": word,
                "current": old,
                "expected": new,
                "status": "ok" if old == new else "changed",
                "file": str(path.relative_to(ROOT)).replace("\\", "/"),
            }
        )
        if old != new:
            row["english"] = new
            changed.append(
                {
                    "rank": row.get("rank"),
                    "article": row.get("article") or "",
                    "word": word,
                    "old": old,
                    "new": new,
                    "file": str(path.relative_to(ROOT)).replace("\\", "/"),
                }
            )
    save(path, doc)
    missing = sorted(set(fixes) - found)
    if missing:
        print(f"Missing in {path.name}: {', '.join(missing)}")
    return changed, reviewed


def write_report(changes: list[dict], reviewed: list[dict]) -> None:
    AUDIT.mkdir(parents=True, exist_ok=True)
    report_json = AUDIT / "learner_translation_pass.json"
    report_md = AUDIT / "learner_translation_pass.md"
    payload = {"changed_this_run": changes, "targeted_entries": reviewed}
    report_json.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    lines = [
        "# Learner Translation Pass",
        "",
        f"Targeted entries checked: **{len(reviewed)}**",
        f"Changed on this run: **{len(changes)}**",
        "",
        "| rank | article | word | current English | expected English | status | file |",
        "|---:|:---:|---|---|---|---|---|",
    ]
    for row in sorted(reviewed, key=lambda r: (r.get("rank") is None, r.get("rank") or 0, r["word"])):
        lines.append(
            f"| {row['rank']} | {row['article']} | {row['word']} | "
            f"{row['current']} | {row['expected']} | {row['status']} | `{row['file']}` |"
        )
    report_md.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    changes = []
    reviewed = []
    noun_changes, noun_reviewed = apply_fixes(DATA / "nouns.json", "nouns", NOUN_FIXES)
    verb_changes, verb_reviewed = apply_fixes(DATA / "verbs.json", "verbs", VERB_FIXES)
    adj_changes, adj_reviewed = apply_fixes(DATA / "adjectives.json", "adjectives", ADJECTIVE_FIXES)
    changes.extend(noun_changes)
    changes.extend(verb_changes)
    changes.extend(adj_changes)
    reviewed.extend(noun_reviewed)
    reviewed.extend(verb_reviewed)
    reviewed.extend(adj_reviewed)
    write_report(changes, reviewed)
    print(f"Applied {len(changes)} learner translation fixes")


if __name__ == "__main__":
    main()
