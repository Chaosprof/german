def main() -> None:
    doc = json.loads(NOUNS.read_text(encoding="utf-8"))
    applied = []
    missing = set(FIXES)
    for noun in doc["nouns"]:
        word = noun.get("word")
        if word not in FIXES:
            continue
        missing.remove(word)
        new = FIXES[word]
        old = noun.get("english", "")
        if old != new:
            noun["english"] = new
            applied.append((noun.get("rank"), word, old, new))

    NOUNS.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    other_applied = {}
    for filename, key, fixes in [
        ("verbs.json", "verbs", VERB_FIXES),
        ("adjectives.json", "adjectives", ADJECTIVE_FIXES),
    ]:
        path = ROOT / "data" / filename
        other_doc = json.loads(path.read_text(encoding="utf-8"))
        changed = []
        missing_other = set(fixes)
        for row in other_doc[key]:
            word = row.get("word")
            if word not in fixes:
                continue
            missing_other.remove(word)
            new = fixes[word]
            old = row.get("english", "")
            if old != new:
                row["english"] = new
                changed.append((row.get("rank"), word, old, new))
        path.write_text(json.dumps(other_doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        other_applied[filename] = {"applied": len(changed), "missing": sorted(missing_other)}
        applied.extend((rank, word, old, new) for rank, word, old, new in changed)

    print(json.dumps(
        {
            "fixes_defined": len(FIXES),
            "applied": len(applied),
            "missing": sorted(missing),
            "other_files": other_applied,
        },
        ensure_ascii=False,
        indent=2,
    ))
    for rank, word, old, new in sorted(applied, key=lambda row: (row[0] or 0, row[1])):
        print(f"{rank:>5} {word}: {old!r} -> {new!r}")


if __name__ == "__main__":
    main()
