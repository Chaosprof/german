def main():
    n_nouns = 0
    n_adjs = 0
    with open(DATA / "nouns.json", encoding="utf-8") as f:
        nouns = json.load(f)
    for entry in nouns["nouns"]:
        w = entry.get("word")
        if w in NOUN_FILLS and not (entry.get("english") or "").strip():
            entry["english"] = NOUN_FILLS[w]
            n_nouns += 1
    with open(DATA / "nouns.json", "w", encoding="utf-8") as f:
        json.dump(nouns, f, ensure_ascii=False, indent=2)

    with open(DATA / "adjectives.json", encoding="utf-8") as f:
        adjs = json.load(f)
    for entry in adjs["adjectives"]:
        w = entry.get("word")
        if w in ADJ_FILLS and not (entry.get("english") or "").strip():
            entry["english"] = ADJ_FILLS[w]
            n_adjs += 1
    with open(DATA / "adjectives.json", "w", encoding="utf-8") as f:
        json.dump(adjs, f, ensure_ascii=False, indent=2)

    print(f"Filled: nouns={n_nouns}, adjectives={n_adjs}")
    missing_n = sum(1 for e in nouns["nouns"] if not (e.get("english") or "").strip())
    missing_a = sum(1 for e in adjs["adjectives"] if not (e.get("english") or "").strip())
    print(f"Still empty: nouns={missing_n}, adjectives={missing_a}")


if __name__ == "__main__":
    main()
