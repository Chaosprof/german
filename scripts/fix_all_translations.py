# GARBAGE DETECTION
# ═══════════════════════════════════════════════════════════════

def is_garbage(eng):
    if not eng or not eng.strip():
        return True
    patterns = [
        r'-y/-ish$',
        r'-ish/-ic$',
        r'-like/-ly$',
        r'^-like/',
        r'-like/mannered',
        r'-like/moderate',
        r'-able$',        # only when preceded by a dash like "experience-able"
    ]
    for p in patterns:
        if re.search(p, eng):
            # -able: only garbage if it has a dash before "able"
            if p == r'-able$' and '-able' in eng:
                return True
            elif p != r'-able$':
                return True
    return False


